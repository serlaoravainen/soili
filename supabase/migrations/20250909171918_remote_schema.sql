CREATE OR REPLACE FUNCTION public.claim_employee_jobs(p_employee_id text, p_since timestamp with time zone, p_types text[], p_limit integer DEFAULT 200)
 RETURNS SETOF mail_jobs
 LANGUAGE sql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  with candidate as (
    select id
    from public.mail_jobs
    where status = 'queued'
      and created_at >= p_since
      and type = any(p_types)
      and payload->>'employee_id' = p_employee_id
    order by created_at asc
    limit p_limit
  ),
  locked as (
    update public.mail_jobs m
      set status = 'processing',
          processed_at = now(),
          attempt_count = m.attempt_count + 1
    where m.id in (select id from candidate)
      and m.status = 'queued'
    returning m.*
  )
  select * from locked;
$function$
;

CREATE OR REPLACE FUNCTION public.claim_employee_jobs(p_employee_id uuid, p_since timestamp with time zone, p_types text[], p_limit integer DEFAULT 200)
 RETURNS SETOF mail_jobs
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  return query
  with cte as (
    select id
    from mail_jobs
    where status = 'queued'
      and (payload->>'employee_id') = p_employee_id::text
      and type = any(p_types)
      and created_at >= p_since
    order by created_at asc
    limit p_limit
    for update skip locked
  )
  update mail_jobs m
  set status = 'processing'
  from cte
  where m.id = cte.id
  returning m.*;
end;
$function$
;

