CREATE OR REPLACE FUNCTION public.unpublish_shifts(_start_date date, _end_date date)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
begin
  update public.shifts
  set published = false
  where work_date between _start_date and _end_date;

  update public.shift_publications
  set status = 'canceled'
  where start_date = _start_date
    and end_date = _end_date;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.upsert_shifts(_employee_id uuid, _work_date date, _type text, _minutes integer)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
begin
  insert into public.shifts (employee_id, work_date, type, minutes)
  values (_employee_id, _work_date, _type, _minutes)
  on conflict (employee_id, work_date)
  do update set
    type = excluded.type,
    minutes = excluded.minutes;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.upsert_shifts_bulk(_rows jsonb)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
begin
  insert into shifts (employee_id, work_date, type, minutes)
  select (r->>'employee_id')::uuid,
         (r->>'work_date')::date,
         r->>'type',
         (r->>'minutes')::int
  from jsonb_array_elements(_rows) as r
  on conflict (employee_id, work_date)
  do update set type = excluded.type,
                minutes = excluded.minutes;
end;
$function$
